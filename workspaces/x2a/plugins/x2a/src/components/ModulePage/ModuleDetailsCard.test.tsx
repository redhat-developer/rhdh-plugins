import { screen } from '@testing-library/react';
import { renderInTestApp } from '@backstage/test-utils';

import {
  GitRepositoryRef,
  Module,
} from '@red-hat-developer-hub/backstage-plugin-x2a-common';

import { mockUseTranslation } from '../../test-utils/mockTranslations';
import { ModuleDetailsCard } from './ModuleDetailsCard';

jest.mock('../../hooks/useTranslation', () => ({
  useTranslation: mockUseTranslation,
}));

jest.mock('../ArtifactLink', () => ({ ArtifactLink: () => <div /> }));
jest.mock('../ModuleStatusCell', () => ({ ModuleStatusCell: () => <div /> }));

describe('ModuleDetailsCard', () => {
  it('provides a keyboard-accessible artifact description', async () => {
    await renderInTestApp(
      <ModuleDetailsCard
        targetRepository={
          new GitRepositoryRef('https://github.com/org/repo', 'main')
        }
      />,
    );

    expect(
      screen.getByRole('button', {
        name: 'These artifacts are generated by the conversion process and are available for review.',
      }),
    ).toBeInTheDocument();
  });

  it('offers a Codespaces edit action beside migrated sources for GitHub', async () => {
    const module = {
      id: 'module-id',
      name: 'module',
      projectId: 'project-id',
      sourcePath: 'src',
      migrate: {
        artifacts: [
          {
            id: 'artifact-id',
            type: 'migrated_sources',
            value: 'project/ansible/roles/example',
          },
        ],
      },
    } as Module;

    await renderInTestApp(
      <ModuleDetailsCard
        module={module}
        targetRepository={
          new GitRepositoryRef(
            'https://github.com/org/repo.git',
            'feature/codespaces',
          )
        }
      />,
    );

    expect(
      screen.getByRole('link', { name: 'Edit in Codespaces' }),
    ).toHaveAttribute(
      'href',
      'https://codespaces.new/org/repo?ref=feature%2Fcodespaces&devcontainer_path=.devcontainer%2Fansible%2Fdevcontainer.json',
    );
  });

  it('does not offer a Codespaces action for non-GitHub repositories', async () => {
    const module = {
      id: 'module-id',
      name: 'module',
      projectId: 'project-id',
      sourcePath: 'src',
      migrate: {
        artifacts: [
          {
            id: 'artifact-id',
            type: 'migrated_sources',
            value: 'project/ansible/roles/example',
          },
        ],
      },
    } as Module;

    await renderInTestApp(
      <ModuleDetailsCard
        module={module}
        targetRepository={
          new GitRepositoryRef('https://gitlab.com/org/repo', 'main')
        }
      />,
    );

    expect(
      screen.queryByRole('link', { name: 'Edit in Codespaces' }),
    ).not.toBeInTheDocument();
  });
});
